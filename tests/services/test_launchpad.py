def test_apps_keep_the_users_order_and_groups(opened: list[tuple[Any, ...]], tmp_path: Path):
    library = LaunchpadApps()
    layout = library.property("layout")
    assert isinstance(layout, LaunchpadLayout)
    # A to Z the first time
    assert rows(layout) == [CALC, CODE, TERM]

    layout.move(2, 0)
    layout.commit()
    assert rows(layout) == [TERM, CALC, CODE]
    saved = json.loads((tmp_path / apps_module.LAYOUT_FILE).read_text(encoding="utf-8"))
    assert saved == {"order": [TERM, CALC, CODE], "hidden": []}
    # Dropped on another app the two become a group in its place
    assert layout.group(2, 0) == 0
    assert rows(layout) == [("New group", [TERM, CODE]), CALC]
    layout.renameGroup(0, " Dev ")
    layout.moveInGroup(0, CODE, 0)
    assert rows(layout) == [("Dev", [CODE, TERM]), CALC]
    # Taken out, the group left with one app turns back into it
    assert layout.takeOut(0, CODE, 2) == 2
    assert rows(layout) == [TERM, CALC, CODE]
    layout.group(2, 0)
    layout.ungroup(0)
    assert rows(layout) == [TERM, CODE, CALC]

    # An app installed since comes last, one gone leaves, and a group left with one app turns back into it
    layout.group(1, 0)
    layout.sync([CALC, CODE, "New.App"])
    assert rows(layout) == [CODE, CALC, "New.App"]

    # Several apps make a group in the place of the first of them
    assert layout.groupApps(["New.App", CODE]) == 0
    assert rows(layout) == [("New group", [CODE, "New.App"]), CALC]
    # Hidden apps leave the grid and their groups, stay hidden as apps come and go, and come back at the end
    layout.hide([CODE, CALC])
    assert rows(layout) == ["New.App"] and layout.property("hidden") == [CODE, CALC]
    layout.sync([CALC, CODE, "New.App", TERM])
    assert rows(layout) == ["New.App", TERM]
    layout.unhide([CALC])
    assert rows(layout) == ["New.App", TERM, CALC] and layout.property("hidden") == [CODE]

    # Every launchpad shares it, and it is read back as it was saved
    assert LaunchpadApps().property("layout") is layout
    LaunchpadLayout._instance = None  # pyright: ignore[reportPrivateUsage]
    read_back = LaunchpadApps().property("layout")
    assert rows(read_back) == [TERM, CALC] and read_back.property("hidden") == [CODE]

    # Opened as Start opens it; run as administrator and the file's folder only for a desktop app's program file
    library.launch(CALC)
    assert library.actions(CALC) == ["uninstall"]
    assert library.actions(CODE) == ["run_as_admin", "open_file_location", "uninstall"]
    library.run(CALC, "run_as_admin")
    library.run(CODE, "run_as_admin")
    library.run(CODE, "open_file_location")
    assert opened == [
        (f"shell:AppsFolder\\{CALC}", "open", None),
        (CODE_EXE, "runas", None),
        ("explorer.exe", "open", f'/select,"{CODE_EXE}"'),
    ]


def test_the_launchpad_searches_moves_apps_and_makes_a_group(opened: list[tuple[Any, ...]], start: Start):
    register_qml_types()
    engine = QQmlEngine()
    engine.addImportPath(QML_IMPORT_PATH)
    engine.addImageProvider(ICON_PROVIDER, IconImageProvider())
    warnings: list[str] = []

    def collect(errors: list[QQmlError]) -> None:
        warnings.extend(error.toString() for error in errors)

    engine.warnings.connect(collect)
    component = QQmlComponent(engine, QUrl.fromLocalFile(str(BUILTIN_WIDGETS_DIR / "Launchpad" / "Launchpad.qml")))
    widget = create_with_bar(component)
    assert isinstance(widget, QQuickItem), [error.toString() for error in component.errors()]
    host = QQuickWindow()
    widget.setParentItem(host.contentItem())
    library = widget.findChild(LaunchpadApps)
    assert library is not None
    layout = library.property("layout")

    def popup() -> QWindow | None:
        return next((w for w in QGuiApplication.topLevelWindows() if w.title() == "Launchpad" and w.isVisible()), None)

    QMetaObject.invokeMethod(widget, "toggle")
    window = popup()
    assert window is not None
    QGuiApplication.sendEvent(
        window, QKeyEvent(QEvent.Type.KeyPress, Qt.Key.Key_T, Qt.KeyboardModifier.NoModifier, "t")
    )
    # Names starting with what is typed come first
    assert [app["name"] for app in QQmlProperty.read(widget, "results").toVariant()] == ["Terminal", "Calculator"]
    QGuiApplication.sendEvent(
        window, QKeyEvent(QEvent.Type.KeyPress, Qt.Key.Key_Return, Qt.KeyboardModifier.NoModifier)
    )
    assert opened == [(f"shell:AppsFolder\\{TERM}", "open", None)]

    QMetaObject.invokeMethod(widget, "toggle")
    QQmlProperty.write(widget, "dragging", {"appId": TERM, "group": False, "from": "grid", "tile": None})
    # Over the left of Calculator's cell, Terminal moves before it; over the middle of Code's they make a group
    QMetaObject.invokeMethod(widget, "aim", Q_ARG("int", 0), Q_ARG("double", 0.1))
    assert rows(layout) == [TERM, CALC, CODE]
    QMetaObject.invokeMethod(widget, "aim", Q_ARG("int", 2), Q_ARG("double", 0.5))
    assert QQmlProperty.read(widget, "mergeRow") == 2
    QMetaObject.invokeMethod(widget, "endDrag")
    assert rows(layout) == [CALC, ("New group", [CODE, TERM])]
    # The new group opens, its name ready to type
    assert QQmlProperty.read(widget, "openGroup") == 1
    # An app installed meanwhile joins at the end
    start.apps.append(StartApp(MAIL, "Mail", "", ""))
    start.changed.emit()
    assert rows(layout) == [CALC, ("New group", [CODE, TERM]), MAIL]

    # Ctrl+click picks a tile, Shift+click the tiles from it to the one clicked
    QMetaObject.invokeMethod(widget, "pick", Q_ARG("QString", "app:" + CALC), Q_ARG("bool", False))
    QMetaObject.invokeMethod(widget, "pick", Q_ARG("QString", "app:" + MAIL), Q_ARG("bool", True))
    assert QQmlProperty.read(widget, "selection").toVariant() == ["app:" + CALC, "group:1", "app:" + MAIL]
    # A hidden app leaves the search too, unless the hidden apps are shown
    layout.hide([CALC])
    QQmlProperty.write(widget, "query", "calc")
    assert QQmlProperty.read(widget, "results").toVariant() == []
    QQmlProperty.write(widget, "showHidden", True)
    assert [app["name"] for app in QQmlProperty.read(widget, "results").toVariant()] == ["Calculator"]
    assert not warnings
    sip.delete(widget)
    sip.delete(host)
