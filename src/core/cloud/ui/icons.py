def svg_icon(svg: str, size: int, color: str) -> QIcon:
    """Render `svg` at `size` logical pixels in `color`."""
    if QGuiApplication.instance() is None:
        return QIcon()

    screen = QGuiApplication.primaryScreen()
    dpr = float(screen.devicePixelRatio()) if screen is not None else 1.0

    # The theme hands out Qt's #AARRGGBB, which SVG reads as invalid and paints black, so
    # split it into #RRGGBB plus an opacity.
    ink = QColor(color)
    renderer = QSvgRenderer(svg.replace("currentColor", ink.name(QColor.NameFormat.HexRgb)).encode("utf-8"))
    if not renderer.isValid():
        return QIcon()

    pixmap = QPixmap(max(1, int(round(size * dpr))), max(1, int(round(size * dpr))))
    pixmap.setDevicePixelRatio(dpr)
    pixmap.fill(Qt.GlobalColor.transparent)

    painter = QPainter(pixmap)
    painter.setRenderHint(QPainter.RenderHint.Antialiasing, True)
    painter.setOpacity(ink.alphaF())

    # Fitted to the viewBox's proportions, not stretched: these icons are not square.
    art = renderer.defaultSize()
    if art.width() > 0 and art.height() > 0:
        scale = min(size / art.width(), size / art.height())
        width, height = art.width() * scale, art.height() * scale
        target = QRectF((size - width) / 2, (size - height) / 2, width, height)
    else:
        target = QRectF(0, 0, size, size)
    renderer.render(painter, target)
    painter.end()
    return QIcon(pixmap)
